#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 1 ]]; then
    echo 'Использование: ./convert.sh "<playback-url>"' >&2
    exit 1
fi

url=$1
# The upstream converter supports the BBB 2.3 playback path and uses its
# last component as the output filename. Keep the URL itself unchanged.
url_pattern='^https?://[^/?#[:space:]]+/playback/presentation/2\.3/([a-z0-9]{40}-[0-9]{13})([?#][^[:space:]]*)?$'
if [[ ! $url =~ $url_pattern ]]; then
    echo 'Неверный playback URL BigBlueButton 2.3.' >&2
    exit 1
fi
meeting_id=${BASH_REMATCH[1]}

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
if [[ ! -f $script_dir/.env ]]; then
    echo 'Файл .env не найден. Сначала запустите deploy.sh.' >&2
    exit 1
fi
# .env is a local shell configuration file generated by deploy.sh.
unset COPY_TO_LOCATION
source "$script_dir/.env"
if [[ ${COPY_TO_LOCATION:-} != /* || $COPY_TO_LOCATION == *:* ]]; then
    echo 'COPY_TO_LOCATION должен быть абсолютным путём без двоеточия.' >&2
    exit 1
fi
mkdir -p -- "$COPY_TO_LOCATION"

echo "Конвертация $meeting_id; результат: $COPY_TO_LOCATION/$meeting_id.mp4"
# The original image opens REC_URL in Chrome and writes to processed/.
# Run in the foreground so the caller can wait for the one-off job.
docker run --rm \
    -v "$COPY_TO_LOCATION:/usr/src/app/processed" \
    --env "REC_URL=$url" \
    manishkatyan/bbb-mp4
