#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 1 ]]; then
    echo 'Использование: ./convert.sh "<playback-url>"' >&2
    exit 1
fi

url=$1
# The upstream converter supports the BBB 2.3 playback path and uses its
# last component as the output filename. Keep the URL itself unchanged.
url_pattern='^https?://[^/?#[:space:]]+/playback/presentation/2\.3/([a-z0-9]{40}-[0-9]{13})([?#][^[:space:]]*)?$'
if [[ ! $url =~ $url_pattern ]]; then
    echo 'Неверный playback URL BigBlueButton 2.3.' >&2
    exit 1
fi
meeting_id=${BASH_REMATCH[1]}

script_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)
if [[ ! -f $script_dir/.env ]]; then
    echo 'Файл .env не найден. Сначала запустите deploy.sh.' >&2
    exit 1
fi
# .env is a local shell configuration file generated by deploy.sh.
job_output=${BBB_MP4_OUTPUT_LOCATION:-}
unset COPY_TO_LOCATION
source "$script_dir/.env"
if [[ -n $job_output ]]; then COPY_TO_LOCATION=$job_output; fi
if [[ ${COPY_TO_LOCATION:-} != /* || $COPY_TO_LOCATION == *:* ]]; then
    echo 'COPY_TO_LOCATION должен быть абсолютным путём без двоеточия.' >&2
    exit 1
fi
mkdir -p -- "$COPY_TO_LOCATION"

echo "Конвертация $meeting_id; результат: $COPY_TO_LOCATION/$meeting_id.mp4"
# The original image opens REC_URL in Chrome and writes to processed/.
# Run in the foreground so the caller can wait for the one-off job.
container_args=()
if [[ -n ${BBB_MP4_CONTAINER_NAME:-} ]]; then
    if [[ ! $BBB_MP4_CONTAINER_NAME =~ ^bbb-mp4-[a-f0-9]{32}$ ]]; then
        echo 'Неверное имя контейнера задания.' >&2
        exit 1
    fi
    container_args=(--name "$BBB_MP4_CONTAINER_NAME")
fi
# Web jobs pass a validated snapshot; plain CLI calls retain upstream defaults.
if [[ -n ${BBB_MP4_SIZE:-} ]]; then
    if [[ ! $BBB_MP4_SIZE =~ ^(640x360|854x480|1280x720|1280x800|1920x1080)$ ]] ||
       [[ ! ${BBB_MP4_VIDEO_BITRATE:-} =~ ^[0-9]{1,5}$ ]] ||
       [[ ! ${BBB_MP4_AUDIO_BITRATE:-} =~ ^[0-9]{1,3}$ ]] ||
       (( 10#$BBB_MP4_VIDEO_BITRATE < 250 || 10#$BBB_MP4_VIDEO_BITRATE > 50000 ||
          10#$BBB_MP4_AUDIO_BITRATE < 32 || 10#$BBB_MP4_AUDIO_BITRATE > 512 )) ||
       [[ ! ${BBB_MP4_PRESET:-} =~ ^(ultrafast|superfast|veryfast|faster|fast|medium|slow)$ ]] ||
       [[ $script_dir == *:* || ! -f $script_dir/ffmpeg-cmd.sh ]]; then
        echo 'Неверные параметры кодирования или путь к скрипту.' >&2
        exit 1
    fi
    container_args+=(-v "$script_dir/ffmpeg-cmd.sh:/usr/src/app/ffmpeg-cmd.sh:ro"
        --env "BBB_MP4_SIZE=$BBB_MP4_SIZE"
        --env "BBB_MP4_VIDEO_BITRATE=$BBB_MP4_VIDEO_BITRATE"
        --env "BBB_MP4_AUDIO_BITRATE=$BBB_MP4_AUDIO_BITRATE"
        --env "BBB_MP4_PRESET=$BBB_MP4_PRESET")
fi
docker run --rm "${container_args[@]}" \
    -v "$COPY_TO_LOCATION:/usr/src/app/processed" \
    --env "REC_URL=$url" \
    manishkatyan/bbb-mp4
